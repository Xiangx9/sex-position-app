/* 火柴人线宽：躯干最粗，腿次之，手臂最细 */
const W_TORSO = 6;
const W_LEG = 5;
const W_ARM = 4;
const HEAD_R = 8;
const BUST_R = 4;

/** 两点连成一根线段（火柴人的一根骨头） */
function limb(x1, y1, x2, y2, w, o = 1) {
  return { t: "s", x1, y1, x2, y2, w, o };
}

/** 三个关节 → 两段肢体 */
function chain(p, w) {
  return [limb(p[0], p[1], p[2], p[3], w), limb(p[2], p[3], p[4], p[5], w)];
}

/**
 * 展开成绘制顺序：远侧肢体 → 躯干 → 近侧肢体 → 头
 * 远侧肢体半透明，形成前后层次。
 */
export function buildParts(p) {
  const far = [];
  const near = [];
  const push = (list, arr) => arr.forEach((s) => list.push(s));

  (p.legs || []).forEach((l) => push(l.far ? far : near, chain(l.p, W_LEG)));
  (p.arms || []).forEach((a) => push(a.far ? far : near, chain(a.p, W_ARM)));

  const body = [];
  if (p.torso) body.push(limb(p.torso[0], p.torso[1], p.torso[2], p.torso[3], W_TORSO));
  // 女性特征：胸部一个圆点（火柴人风格下最小可辨识）
  if (p.sex === "f" && p.bust) body.push({ t: "c", cx: p.bust[0], cy: p.bust[1], r: BUST_R });

  const head = p.head ? [{ t: "c", cx: p.head[0], cy: p.head[1], r: HEAD_R }] : [];

  return {
    far: far.map((s) => ({ ...s, o: 0.5 })),
    body,
    near,
    head,
  };
}

/* ---------- 让两个人贴得更近 ---------- */
/**
 * 以「骨盆」为贴合锚点：把 B 朝 A 的骨盆方向拉近 CLOSE_FACTOR 比例。
 * 这样不用逐个手改 19+ 个姿势的坐标，也不会破坏姿势本身的几何。
 */
export const CLOSE_FACTOR = 0.35;

function anchorOf(p) {
  if (!p) return null;
  if (p.hips) return [p.hips[0], p.hips[1]];
  if (p.torso) return [p.torso[2], p.torso[3]];
  return null;
}

export function closeOffset(pose) {
  const a = anchorOf(pose.A);
  const b = anchorOf(pose.B);
  if (!a || !b) return [0, 0];
  return [(a[0] - b[0]) * CLOSE_FACTOR, (a[1] - b[1]) * CLOSE_FACTOR];
}

