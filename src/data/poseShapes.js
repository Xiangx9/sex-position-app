/**
 * 手绘姿势库 · 骨骼坐标版
 *
 * 与之前失败的参数化引擎的区别：
 *   这里【每个姿势都写死关节坐标】，肢体只是把两个关节连成一根圆角长条，
 *   不做任何角度推算、不做嵌套 transform。改一个姿势不会牵动其它姿势。
 *
 * 一个人这样描述：
 *   head:  [cx, cy, r]                 头
 *   torso: [肩x, 肩y, 髋x, 髋y, 粗]     躯干（肩到髋的一根粗条）
 *   hips:  [cx, cy, r]                 臀部（可选，让坐姿/跪姿更厚实）
 *   bust:  [cx, cy, r]                 女性胸部特征（可选）
 *   arms:  [{ p:[肩,肘,腕], far:true }] 手臂，far 表示在身体另一侧（半透明）
 *   legs:  [{ p:[髋,膝,踝], far:true }] 腿
 *   approach: [dx, dy]                 分步动画中「还没靠近」时的位移
 *   tag:   [x, y]                      标注位置
 *
 * 画布 260 × 190。地面 y = 158，床垫面 y = 138。
 * 配色：女 = 暖橙 #F08A3E，男 = 深蓝 #1E3A6B，都是实心剪影。
 */

export const FLOOR = 158;
export const MATTRESS_TOP = 138;

